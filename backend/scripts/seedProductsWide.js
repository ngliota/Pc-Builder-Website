const seedCategory = async (category, baseItems) => {
  const processed = []
  for (const item of baseItems) {
    const existing = await Product.findOne({ where: { name: item.name, category } })
    const payload = {
      name: item.name,
      brand: item.brand || "Generic",
      category,
      price: item.price,
      stock: Math.max(100, item.stock || 100),
      is_active: true,
    }
    if (existing) {
      await existing.update(payload)
      processed.push({ name: item.name, action: "updated" })
    } else {
      await Product.create(payload)
      processed.push({ name: item.name, action: "created" })
    }
  }
  return processed
}

const run = async () => {
  try {
    const summary = []
    for (const [category, items] of Object.entries(baseCatalog)) {
      const processed = await seedCategory(category, items)
      summary.push({ category, count: processed.length })
      console.log(`Category ${category}: processed ${processed.length} items`)
    }
    console.table(summary)
  } catch (err) {
    console.error("Wide seed failed:", err.message)
  } finally {
    await db.close()
  }
}

run()
